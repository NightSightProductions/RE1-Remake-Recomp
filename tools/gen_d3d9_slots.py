# usage: gen_d3d9_slots.py d3d9_bridge.cpp out.h: method names and stack slots (incl. this) per D3D9 interface
# vtable, from the bridge's tables (for the native renderer's traps)
import re, sys
src = open(sys.argv[1]).read()
macros = {}
for m in re.finditer(r"#define (UNK|RESOURCE|BASETEX)\b(.*?)(?:\n(?!\s{4})|\n\n)", src, re.S):
    macros[m.group(1)] = m.group(2).replace("\\\n", " ")
def entries(body):
    for k, v in macros.items(): body = re.sub(r"\b%s\b" % k, v, body)
    out = []
    for m in re.finditer(r'\b(FWD|SPC)\("(\w+)",\s*("([^"]*)"|\d+)', body):
        if m.group(1) == "FWD": sig = m.group(4); n = 1 + len(sig) - sig.count("O")
        else: n = int(m.group(3))
        out.append((m.group(2), n))
    return out
tables = {}
for m in re.finditer(r"const ComMethod (\w+)\[\] = \{(.*?)\};", src, re.S):
    tables[m.group(1)] = entries(m.group(2))
with open(sys.argv[2], "w") as f:
    f.write("// generated by tools/gen_d3d9_slots.py from framework/win32/runtime/d3d9_bridge.cpp\n#pragma once\n")
    f.write("typedef struct { const char *name; unsigned char nargs; } RnSlot;\n")
    for t, es in tables.items():
        f.write("static const RnSlot rn_slots_%s[] = {%s};\n" % (t, ", ".join('{"%s", %d}' % e for e in es)))
        f.write("#define RN_NSLOTS_%s %d\n" % (t, len(es)))
print({t: len(es) for t, es in tables.items()})
